// ===================== وردةُ رقم الآية =====================
// في المصحف المطبوع تُختم الآيةُ بوردةٍ مزخرفة: دائرةٌ مسنَّنةٌ بأصدافٍ صغيرة
// وداخلها الرقم. وهي **علامةُ وقفٍ قبل أن تكون زخرفة**: العينُ تلتقطها فتعرف
// أين انتهت الآية بلا أن تقرأ الرقم.
//
// ولماذا تُرسم هنا ولا تُترك للخطّ؟ لأنّ خطّ المصحف يكتبها قوسين مزخرفين حول
// الرقم (`﴿٩﴾`) — وهما في القياس أعرضُ من الوردة وأثقلُ في العين، ومصدرُ التخطيط
// قاس عرض السطر بهما. فالحلُّ في `AyahNumber`: نصُّ المصدر يبقى شبحاً يحجز عرضه
// المقيس، وهذه الوردةُ تُرسم في موضعه. أمّا وردةُ الخطّ نفسه (`۝`) فبيضاويةٌ
// فارغة والرقمُ خارجها — لا تصلح.
//
// نقيّةٌ بلا DOM: مسارُ SVG محسوبٌ من عدد الأصداف ونصف القطر، فيعبر إلى الغلاف
// الأصليّ كما هو (راجع `docs/APP-STORE-PLAN.md`).

/** مربّعُ الرسم: مئةٌ في مئة، والمركز في وسطه. */
export const ROSETTE_BOX = 100;

/**
 * دائرةٌ مسنَّنةٌ بأصدافٍ متساوية: نقاطٌ على محيطٍ نصفُ قطره `radius`، وبين كلّ
 * نقطتين قوسٌ ينتفخ إلى الخارج. `bulge` نسبةُ نصف قطر القوس إلى نصف الوتر —
 * الواحدُ يعطي نصفَ دائرةٍ تامّة، وما فوقه يفلطح الصدفة.
 */
export function scallopPath(count = 12, radius = 36, bulge = 1.2): string {
  const c = ROSETTE_BOX / 2;
  const at = (i: number) => {
    const a = (2 * Math.PI * i) / count - Math.PI / 2;
    return [c + radius * Math.cos(a), c + radius * Math.sin(a)] as const;
  };
  const arc = ((2 * radius * Math.sin(Math.PI / count)) / 2) * bulge;
  const [x0, y0] = at(0);
  let d = `M ${x0.toFixed(2)} ${y0.toFixed(2)}`;
  for (let i = 1; i <= count; i++) {
    const [x, y] = at(i % count);
    d += ` A ${arc.toFixed(2)} ${arc.toFixed(2)} 0 0 1 ${x.toFixed(2)} ${y.toFixed(2)}`;
  }
  return `${d} Z`;
}

/** مسارُ الوردة المعتمد في اللوح — يُحسب مرّةً واحدة. */
export const ROSETTE_PATH = scallopPath();
/** نصفُ قطر الحلقة الداخلية (تحيط بالرقم كما في المطبوع). */
export const ROSETTE_INNER = 27;
