// ===================== إصدار التطبيق =====================
// رقم الإصدار في «مدار» يعكس **عدد التعديلات الجوهرية منذ أوّل نسخة مستقرة**، لا
// إصداراتٍ تسويقية. القاعدة:
//   • `APP_BUILD` عدّادٌ تسلسليّ يرتفع **بواحد** مع كل تعديلٍ جوهريّ يُدفَع
//     للمستودع (ميزة · إصلاح · مهاجرة بيانات).
//   • لا قفزَ ولا إعادةَ تعيينٍ أبداً: الرقم يكبر فقط.
//   • `APP_VERSION` مشتقٌّ منه (`0.1.<build>`) وهو ما يُكتب في `package.json`.
//
// هذا الملف هو **المصدر الوحيد** للرقم. `scripts/check-version.mjs` يُشغَّل قبل
// البناء ويمنع انحراف `package.json` عنه (كان الإصدار مكتوباً بيدٍ في صفحة
// الإعدادات وفي package.json، فتخلّف أحدهما عن الآخر بلا إشعار).
// للرفع: `npm run bump` (يحدّث الملفين معاً)، ثمّ سطرٌ في ROADMAP.md.
//
// أُوقِف العدّاد على 292 عند اعتماد النظام: تاريخ المستودع الحقيقي وقتها 291
// تعديلاً، وهذا التعديل هو 292 — فالرقم يعكس التطوير الفعليّ من أول يوم بدل أن
// يبدأ من صفرٍ يكذب على عمر المشروع.
export const APP_BUILD = 385;

export const APP_VERSION = `0.1.${APP_BUILD}`;
