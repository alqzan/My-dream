// ===================== تبنّي لقطة السحابة بلا فقد تعديلٍ محليّ =====================
// بين قراءة السحابة وتطبيقها على المتجر تمرّ آلافُ الميلي ثانية: نداءٌ شبكيّ،
// ثمّ `hydrateCloudPhotos` (تنزيلُ صور)، ثمّ `inlineCachedMedia`. والمستخدم لا
// ينتظر: يسجّل عمليةً أو يكتب مذكرةً في هذه النافذة بالضبط.
//
// **الفخّ الذي وُلدت هذه الوحدة لسدّه**: كانت اللقطة المحلّية تُؤخذ **مرّةً**
// قبل الانتظار، فيُبنى عليها الدمج، ثمّ يُطبَّق `hydrate` بعد الانتظار — فيمحو
// تعديلاً وقع بعد أخذ اللقطة. والأسوأ: الاشتراك الذي يلتقط التعديلات لم يكن قد
// سُجّل بعد، فلا المتجر احتفظ به ولا السحابة رأته. عمليةٌ تختفي بلا أثر.
//
// **الحلّ**: عدّادُ تعديلٍ محليّ يُقرأ قبل الدمج ويُراجَع بعد الانتظار. إن تحرّك
// أُعيد الدمج على أحدث `snapshot()` — فلا يُطبَّق على المتجر إلا ناتجٌ يشمل كلّ
// تعديلٍ وقع حتى لحظة التطبيق.
//
// **ولا يُكسر ترتيب الوسائط**: الدمج يقع على `cloud` وهي ما تزال تحمل
// `photoRefs`/`audioRefs` (لا على نسخةٍ مُرطَّبة)، والترطيب يأتي بعده وللعرض
// وحده — كما تنصّ قاعدة المستودع. إعادةُ الجولة تعيد الترتيب نفسه من أوّله، لا
// ترقّع نسخةً مُرطَّبة.
//
// نقيّةٌ بالكامل: لا DOM ولا Firebase ولا متجر — دوالٌّ مُمرَّرة فقط.
import type { AppData } from "./types";
import { mergeAppData } from "./merge";

/** أقصى إعادةِ دمجٍ قبل اللجوء إلى الطيّ المباشر (تعديلٌ متدفّق بلا انقطاع). */
export const MAX_ADOPT_ROUNDS = 3;

export interface AdoptResult {
  /**
   * ما يُطبَّق على المتجر: الاتحاد مُرطَّباً للعرض. `Partial` لأنّ
   * `mergeLocalPhotos` تعلن هذا النوع — والكائن في الواقع كاملُ الحقول.
   */
  display: Partial<AppData>;
  /** ما يُحفظ في السحابة: الاتحاد **غنيّاً بالمراجع** لا نسخة العرض. */
  save: AppData;
  /** كم جولةً لزمت (1 في الحالة السويّة) — للاختبار والتشخيص. */
  rounds: number;
}

export interface AdoptOptions {
  /** أحدثُ حالة الجهاز الآن. تُنادى في كلّ جولة — لا تُخزَّن. */
  snapshot: () => AppData;
  /** لقطة السحابة **بمراجع وسائطها** كما وصلت. */
  cloud: AppData;
  /**
   * الاتحاد (بالمراجع) + الجهاز → نسخةُ العرض. هنا يقع `hydrateCloudPhotos` ثمّ
   * `mergeLocalPhotos` ثمّ `inlineCachedMedia` — ولا يقع شيءٌ منها قبل الدمج.
   */
  toDisplay: (merged: AppData, local: AppData) => Promise<Partial<AppData>>;
  /** عدّادٌ يرتفع مع كلّ تعديلٍ محليّ (لا يرتفع للتعديلات القادمة من السحابة). */
  editSeq: () => number;
  maxRounds?: number;
}

/**
 * ادمج لقطة السحابة مع الجهاز وأنتِج نسختَي (العرض · الحفظ) بحيث لا يسقط تعديلٌ
 * محليّ وقع أثناء الانتظار.
 */
export async function adoptCloudSnapshot({
  snapshot, cloud, toDisplay, editSeq, maxRounds = MAX_ADOPT_ROUNDS,
}: AdoptOptions): Promise<AdoptResult> {
  for (let round = 1; ; round++) {
    const mark = editSeq();
    const local = snapshot();
    // الدمج على المراجع — قبل أيّ ترطيب.
    const save = mergeAppData(local, cloud);
    const display = await toDisplay(save, local);
    // لم يتحرّك شيءٌ أثناء الانتظار: الناتج يمثّل الجهاز كما هو الآن.
    if (editSeq() === mark) return { display, save, rounds: round };

    if (round >= maxRounds) {
      // تعديلٌ ما زال يتدفّق بعد جولاتٍ — لا نُعيد الترطيب إلى ما لا نهاية ولا
      // نطبّق ناتجاً ناقصاً. نطوي أحدثَ حالةِ الجهاز فوق الاثنين: هي الأحدث
      // ختماً فتصير الأساس، ويُحسم كلّ عنصرٍ بطابعه هو. مراجعُ السحابة في
      // `save` باقيةٌ (الاتحاد لا يُسقط مرجعاً)، ووسائطُ الجهاز تنضمّ للعرض كما
      // يفعل `mergeLocalPhotos` أصلاً.
      const fresh = snapshot();
      return {
        // `{...fresh, ...display}` شكليٌّ لا أكثر: نسخةُ العرض كاملةُ الحقول
        // فعلاً، لكنّ نوعها المعلن `Partial` — والأساس يسدّ ما لم تعلنه.
        display: mergeAppData(fresh, { ...fresh, ...display }),
        save: mergeAppData(fresh, save),
        rounds: round,
      };
    }
  }
}
